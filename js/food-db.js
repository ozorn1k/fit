const FOOD_DB = FOOD_RAW.trim().split('\n').map(line => {
  const [name, kcal, p, f, c, port] = line.split('|');
  const item = { name, kcal: +kcal, p: +p, f: +f, c: +c };
  if (port) {
    const [pn, pg] = port.split(':');
    item.portName = pn;
    item.portG = +pg;
  }
  return item;
});

/* Все продукты: база + пользовательские */
function allFoods() {
  return S.customFoods.concat(FOOD_DB);
}

/* Поиск без учёта регистра, свои продукты первыми, совпадение с начала слова выше */
function searchFood(q) {
  q = (q || '').trim().toLowerCase();
  if (!q) {
    const recent = S.recent.map(n => allFoods().find(f => f.name.toLowerCase() === n.toLowerCase())).filter(Boolean);
    return recent.length ? recent.slice(0, 12) : FOOD_DB.slice(0, 14);
  }
  const list = allFoods();
  const starts = [], inner = [];
  for (const f of list) {
    const n = f.name.toLowerCase();
    if (n.startsWith(q)) starts.push(f);
    else if (n.includes(q)) inner.push(f);
  }
  return starts.concat(inner).slice(0, 30);
}

function rememberFood(name) {
  S.recent = [name].concat(S.recent.filter(n => n !== name)).slice(0, 20);
}
